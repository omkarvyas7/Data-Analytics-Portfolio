def pct(x: float, d: int = 1) -> str:
    return f"{x * 100:.{d}f}%"


def usd(x: float, d: int = 0) -> str:
    return f"${x:,.{d}f}"


def num(x: float, d: int = 0) -> str:
    return f"{x:,.{d}f}"


def load_facts() -> dict:
    m = json.loads((PROC / "metrics.json").read_text())
    con = sqlite3.connect(DB)
    q = lambda s: pd.read_sql_query(s, con)  # noqa: E731
    seg = pd.read_csv(PROC / "04_defect_rate_by_segment.csv")
    sr = lambda dim, s: float(seg[(seg.dimension == dim) & (seg.segment == s)].defect_rate.iloc[0])  # noqa: E731
    f = dict(m)
    f["seg"] = sr
    f["photo"] = q("SELECT phase, AVG(photo_step_done) AS r FROM v_units GROUP BY phase").set_index("phase").r.to_dict()
    nh = q("SELECT phase, AVG(is_defect) AS r, COUNT(*) AS n FROM v_audited WHERE tenure_days < 30 GROUP BY phase").set_index("phase")
    f["newhire_rate"], f["newhire_n"] = nh.r.to_dict(), nh.n.to_dict()
    el = q("SELECT phase, AVG(is_defect) AS r FROM v_audited WHERE category = 'Electronics' GROUP BY phase").set_index("phase").r
    f["elec_rate"] = el.to_dict()
    ob = q("SELECT phase, AVG(is_defect) AS r FROM v_audited WHERE audited_disposition = 'OPEN_BOX' GROUP BY phase").set_index("phase").r
    f["ob_rate"] = ob.to_dict()
    ni = q("SELECT phase, AVG(is_defect) AS r FROM v_audited WHERE shift = 'Night' GROUP BY phase").set_index("phase").r
    f["night_rate_by_phase"] = ni.to_dict()
    dirn = q("SELECT defect_direction, COUNT(*) AS n FROM v_audited WHERE phase='Baseline' AND is_defect=1 GROUP BY 1").set_index("defect_direction").n
    f["upgrade_share"] = float(dirn.get("Upgrade (graded too high)", 0) / dirn.sum())
    wk = q("SELECT AVG(n) AS n FROM (SELECT week_start, COUNT(*) n FROM v_units WHERE phase='Control' GROUP BY 1)")
    f["control_units_per_week"] = float(wk.n.iloc[0])
    f["months"] = q("SELECT month, COUNT(*) AS n FROM v_units GROUP BY month").set_index("month").n.to_dict()
    con.close()
    f["dq"] = pd.read_csv(PROC / "data_quality_log.csv")
    f["pareto"] = pd.read_csv(PROC / "03_defect_pareto_by_cause.csv")
    f["base"] = pd.read_csv(PROC / "02_baseline_defect_rate_dpmo_sigma.csv")
    f["pilot_tbl"] = pd.read_csv(PROC / "08_pilot_pre_post.csv")
    f["tests"] = pd.read_csv(PROC / "hypothesis_tests.csv")
    f["odds"] = pd.read_csv(PROC / "logit_odds_ratios.csv")
    f["cap"] = pd.read_csv(PROC / "capability.csv")
    f["vs"] = pd.read_csv(PROC / "10_value_stream_stage_times.csv")
    pc = pd.read_csv(PROC / "p_chart_data.csv")
    ctl = pc[pc.phase == "Control"]
    nbar = ctl.audited_units.mean()
    p = m["pchart_control_pbar"]
    f["ctl_ucl_avg_n"] = p + 3 * (p * (1 - p) / nbar) ** 0.5
    f["ctl_lcl_avg_n"] = max(0.0, p - 3 * (p * (1 - p) / nbar) ** 0.5)
    f["ctl_nbar"] = nbar
    f["ctl_weeks_le_target"] = int((ctl.defect_rate <= m["target_defect_rate"]).sum())
    return f


def table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(out)



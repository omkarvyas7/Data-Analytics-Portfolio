"""Build excel/DMAIC_Defect_Tracker.xlsx with openpyxl.

Tabs: README, Audit_Data (Excel table), Pareto (COUNTIFS + cumulative %), Segment_Pivot (COUNTIFS/SUMIFS
pivot-style matrix), PChart_Data (UCL/LCL formulas), Weekly_Feed (SQL 09 output), KPI_Tracker
(INDEX/MATCH + XLOOKUP, RAG conditional formatting), Scenario (target defect rate -> $ impact).
Cells hold real Excel formulas, so values calculate when the file is opened in Excel.
"""
from __future__ import annotations

import json
import sqlite3
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.chart import BarChart, LineChart, Reference
from openpyxl.formatting.rule import CellIsRule, FormulaRule
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.table import Table, TableStyleInfo

ROOT = Path(__file__).resolve().parents[1]
PROC = ROOT / "data" / "processed"
DB = ROOT / "data" / "returns_dmaic.db"
OUT = ROOT / "excel" / "DMAIC_Defect_Tracker.xlsx"

HDR = PatternFill("solid", fgColor="1F3B57")
INPUT = PatternFill("solid", fgColor="FFF2CC")
GREEN = PatternFill("solid", fgColor="C6EFCE")
AMBER = PatternFill("solid", fgColor="FFEB9C")
RED = PatternFill("solid", fgColor="FFC7CE")
WHITE_B = Font(color="FFFFFF", bold=True)
THIN = Border(*(Side(style="thin", color="BFBFBF"),) * 4)


def header(ws, row: int, cols: list[str], start_col: int = 1) -> None:
    for j, c in enumerate(cols):
        cell = ws.cell(row=row, column=start_col + j, value=c)
        cell.fill, cell.font = HDR, WHITE_B
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)


def widths(ws, w: dict[str, float]) -> None:
    for k, v in w.items():
        ws.column_dimensions[k].width = v


def main() -> None:
    OUT.parent.mkdir(exist_ok=True)
    m = json.loads((PROC / "metrics.json").read_text())
    con = sqlite3.connect(DB)
    aud = pd.read_sql_query(
        "SELECT audit_id, unit_id, op_date, week_start, phase, site_id, shift, category, tenure_days, tenure_band, "
        "sop_version, photo_step_done, assigned_disposition, audited_disposition, defect_cause, "
        "ROUND(recovery_leakage_usd, 2) AS recovery_leakage_usd, waste_flag "
        "FROM v_audited ORDER BY op_date, audit_id", con)
    con.close()
    aud["defect_cause"] = aud.defect_cause.fillna("")
    for c in ["op_date", "week_start"]:
        aud[c] = pd.to_datetime(aud[c])
    weekly = pd.read_csv(PROC / "09_weekly_control_chart_feed.csv", parse_dates=["week_start"])
    pareto = pd.read_csv(PROC / "03_defect_pareto_by_cause.csv")

    wb = Workbook()
    # ---------------------------------------------------------------- README
    ws = wb.active
    ws.title = "README"
    lines = [
        ("DMAIC Defect Tracker: returns disposition quality", True),
        ("Synthetic data generated by src/generate_data.py. No Amazon or employer data is used.", False),
        ("", False),
        ("Tab guide", True),
        ("Audit_Data: one row per QA-audited unit (Excel table tblAudit). is_defect is a formula: assigned <> audited.", False),
        ("Pareto: baseline defects by root cause with COUNTIFS, share and cumulative %, plus a combo chart.", False),
        ("Segment_Pivot: pivot-style matrix of defect rate by site/shift/category x phase using COUNTIFS/SUMIFS.", False),
        ("PChart_Data: weekly n, defects, p, centre line and 3-sigma UCL/LCL formulas, plus a line chart.", False),
        ("Weekly_Feed: output of sql/09_weekly_control_chart_feed.sql (values).", False),
        ("KPI_Tracker: weekly KPIs pulled with INDEX/MATCH and XLOOKUP, RAG status vs target (conditional formatting).", False),
        ("Scenario: change the yellow target defect rate cell to size annual recovery $ impact.", False),
        ("", False),
        ("Yellow cells are inputs. Formulas recalculate on open in Excel 365 / Excel 2021 (XLOOKUP needs 365/2021).", False),
    ]
    for i, (t, b) in enumerate(lines, 1):
        ws.cell(row=i, column=1, value=t).font = Font(bold=b, size=13 if i == 1 else 11)
    ws.column_dimensions["A"].width = 120

    # ---------------------------------------------------------------- Audit_Data
    ws = wb.create_sheet("Audit_Data")
    cols = ["audit_id", "unit_id", "op_date", "week_start", "phase", "site_id", "shift", "category",
            "tenure_days", "tenure_band", "sop_version", "photo_step_done", "assigned_disposition",
            "audited_disposition", "is_defect", "defect_cause", "recovery_leakage_usd", "waste_flag"]
    ws.append(cols)
    for r in aud.itertuples(index=False):
        ws.append([r.audit_id, r.unit_id, r.op_date.to_pydatetime(), r.week_start.to_pydatetime(), r.phase,
                   r.site_id, r.shift, r.category, r.tenure_days, r.tenure_band, r.sop_version,
                   r.photo_step_done, r.assigned_disposition, r.audited_disposition, None, r.defect_cause,
                   r.recovery_leakage_usd, r.waste_flag])
    n = len(aud) + 1
    for i in range(2, n + 1):
        ws.cell(row=i, column=15, value=f"=IF(M{i}<>N{i},1,0)")
        ws.cell(row=i, column=3).number_format = "yyyy-mm-dd"
        ws.cell(row=i, column=4).number_format = "yyyy-mm-dd"
    tab = Table(displayName="tblAudit", ref=f"A1:R{n}")
    tab.tableStyleInfo = TableStyleInfo(name="TableStyleMedium2", showRowStripes=True)
    ws.add_table(tab)
    ws.freeze_panes = "A2"
    for j, c in enumerate(cols, 1):
        ws.column_dimensions[get_column_letter(j)].width = max(11, len(c) + 2)
    rng = lambda col: f"Audit_Data!${col}$2:${col}${n}"  # noqa: E731
    PH, SITE, SHIFT, CAT, WEEK, DEF, CAUSE, LEAK = (rng(c) for c in "EFGHDOPQ")

    # ---------------------------------------------------------------- Pareto
    ws = wb.create_sheet("Pareto")
    ws["A1"] = "Pareto of baseline disposition defects by root cause (phase = Baseline)"
    ws["A1"].font = Font(bold=True, size=13)
    header(ws, 3, ["Defect cause", "Defects", "Share", "Cumulative %", "In first 80%", "Leakage $ (sample)"])
    k0 = 4
    for i, cause in enumerate(pareto.defect_cause):
        r = k0 + i
        ws.cell(row=r, column=1, value=cause)
        ws.cell(row=r, column=2, value=f'=COUNTIFS({CAUSE},A{r},{PH},"Baseline")')
        ws.cell(row=r, column=3, value=f"=B{r}/SUM($B${k0}:$B${k0 + len(pareto) - 1})").number_format = "0.0%"
        ws.cell(row=r, column=4, value=f"=SUM($B${k0}:B{r})/SUM($B${k0}:$B${k0 + len(pareto) - 1})").number_format = "0.0%"
        prev = f"D{r - 1}" if i else "0"
        ws.cell(row=r, column=5, value=f'=IF({prev}<0.8,"Yes","No")')
        ws.cell(row=r, column=6, value=f'=SUMIFS({LEAK},{CAUSE},A{r},{PH},"Baseline")').number_format = '"$"#,##0'
    kl = k0 + len(pareto) - 1
    ws.cell(row=kl + 1, column=1, value="Total").font = Font(bold=True)
    ws.cell(row=kl + 1, column=2, value=f"=SUM(B{k0}:B{kl})").font = Font(bold=True)
    ws.cell(row=kl + 1, column=6, value=f"=SUM(F{k0}:F{kl})").number_format = '"$"#,##0'
    ws.conditional_formatting.add(f"E{k0}:E{kl}", CellIsRule(operator="equal", formula=['"Yes"'], fill=GREEN))
    widths(ws, {"A": 34, "B": 10, "C": 9, "D": 13, "E": 16, "F": 16})
    bar = BarChart()
    bar.title = "Pareto: baseline defects by cause"
    bar.y_axis.title = "Defects"
    bar.add_data(Reference(ws, min_col=2, min_row=3, max_row=kl), titles_from_data=True)
    bar.set_categories(Reference(ws, min_col=1, min_row=k0, max_row=kl))
    line = LineChart()
    line.add_data(Reference(ws, min_col=4, min_row=3, max_row=kl), titles_from_data=True)
    line.y_axis.axId = 200
    line.y_axis.title = "Cumulative %"
    line.y_axis.number_format = "0%"
    line.y_axis.scaling.min, line.y_axis.scaling.max = 0, 1
    line.y_axis.crosses = "max"
    bar += line
    bar.height, bar.width = 9, 20
    ws.add_chart(bar, "H3")

    # ---------------------------------------------------------------- Segment_Pivot
    ws = wb.create_sheet("Segment_Pivot")
    ws["A1"] = "Defect rate by segment and DMAIC phase (COUNTIFS / SUMIFS pivot)"
    ws["A1"].font = Font(bold=True, size=13)
    phases = ["Baseline", "Pilot", "Control"]
    row = 3
    for dim, col_rng, values in [("Site", SITE, sorted(aud.site_id.unique())),
                                 ("Shift", SHIFT, ["Day", "Swing", "Night"]),
                                 ("Category", CAT, sorted(aud.category.unique()))]:
        header(ws, row, [dim] + [f"{p} audits" for p in phases] + [f"{p} defect rate" for p in phases] + ["Change vs baseline"])
        for v in values:
            row += 1
            ws.cell(row=row, column=1, value=v)
            for j, p in enumerate(phases):
                ws.cell(row=row, column=2 + j, value=f'=COUNTIFS({col_rng},$A{row},{PH},"{p}")')
                c = ws.cell(row=row, column=5 + j,
                            value=f'=IFERROR(SUMIFS({DEF},{col_rng},$A{row},{PH},"{p}")/{get_column_letter(2 + j)}{row},"")')
                c.number_format = "0.0%"
            ws.cell(row=row, column=8, value=f'=IFERROR(G{row}-E{row},"")').number_format = "+0.0%;-0.0%"
        ws.conditional_formatting.add(f"E{row - len(values) + 1}:G{row}",
                                      CellIsRule(operator="greaterThan", formula=["0.07"], fill=RED))
        row += 3
    widths(ws, {"A": 26, **{get_column_letter(i): 14 for i in range(2, 9)}})

    # ---------------------------------------------------------------- PChart_Data
    ws = wb.create_sheet("PChart_Data")
    ws["A1"] = "p-chart data: weekly network defect proportion with 3-sigma limits"
    ws["A1"].font = Font(bold=True, size=13)
    ws["A2"] = "Baseline p-bar"
    ws["C2"] = "Control p-bar"
    header(ws, 4, ["Week start", "Phase", "Audited (n)", "Defects", "p", "Centre line", "UCL", "LCL", "Signal"])
    weeks = weekly[weekly.partial_week_flag == 0].reset_index(drop=True)
    w0 = 5
    wl = w0 + len(weeks) - 1
    ws["B2"] = f'=SUMIFS(D{w0}:D{wl},B{w0}:B{wl},"Baseline")/SUMIFS(C{w0}:C{wl},B{w0}:B{wl},"Baseline")'
    ws["D2"] = f'=SUMIFS(D{w0}:D{wl},B{w0}:B{wl},"Control")/SUMIFS(C{w0}:C{wl},B{w0}:B{wl},"Control")'
    ws["B2"].number_format = ws["D2"].number_format = "0.00%"
    for i, r in weeks.iterrows():
        x = w0 + i
        ws.cell(row=x, column=1, value=r.week_start.to_pydatetime()).number_format = "yyyy-mm-dd"
        ws.cell(row=x, column=2, value=r.phase)
        ws.cell(row=x, column=3, value=f"=COUNTIFS({WEEK},A{x})")
        ws.cell(row=x, column=4, value=f"=SUMIFS({DEF},{WEEK},A{x})")
        ws.cell(row=x, column=5, value=f"=D{x}/C{x}").number_format = "0.00%"
        ws.cell(row=x, column=6, value=f'=IF(B{x}="Control",$D$2,$B$2)').number_format = "0.00%"
        ws.cell(row=x, column=7, value=f"=F{x}+3*SQRT(F{x}*(1-F{x})/C{x})").number_format = "0.00%"
        ws.cell(row=x, column=8, value=f"=MAX(0,F{x}-3*SQRT(F{x}*(1-F{x})/C{x}))").number_format = "0.00%"
        ws.cell(row=x, column=9, value=f'=IF(E{x}>G{x},"Above UCL",IF(E{x}<H{x},"Below LCL",""))')
    ws.conditional_formatting.add(f"I{w0}:I{wl}", CellIsRule(operator="equal", formula=['"Above UCL"'], fill=RED))
    widths(ws, {"A": 12, "B": 10, "C": 11, "D": 9, "E": 9, "F": 11, "G": 9, "H": 9, "I": 12})
    lc = LineChart()
    lc.title = "p-chart: weekly defect rate with UCL / LCL"
    lc.y_axis.number_format = "0%"
    lc.y_axis.title = "Defect rate"
    for col in [5, 6, 7, 8]:
        lc.add_data(Reference(ws, min_col=col, min_row=4, max_row=wl), titles_from_data=True)
    lc.set_categories(Reference(ws, min_col=1, min_row=w0, max_row=wl))
    for s, color, dash in zip(lc.series, ["1F3B57", "2D6A4F", "D62828", "D62828"], [None, None, "dash", "dash"]):
        s.graphicalProperties.line.solidFill = color
        if dash:
            s.graphicalProperties.line.dashStyle = dash
        s.smooth = False
    lc.height, lc.width = 10, 24
    ws.add_chart(lc, "K4")

    # ---------------------------------------------------------------- Weekly_Feed
    ws = wb.create_sheet("Weekly_Feed")
    wcols = list(weekly.columns)
    header(ws, 1, wcols)
    for r in weekly.itertuples(index=False):
        ws.append([v.to_pydatetime() if isinstance(v, pd.Timestamp) else v for v in r])
    for i in range(2, len(weekly) + 2):
        ws.cell(row=i, column=1).number_format = "yyyy-mm-dd"
    for j, c in enumerate(wcols, 1):
        ws.column_dimensions[get_column_letter(j)].width = max(11, len(c) + 2)
    wf_n = len(weekly) + 1
    wfr = lambda col: f"Weekly_Feed!${col}$2:${col}${wf_n}"  # noqa: E731

    # ---------------------------------------------------------------- KPI_Tracker
    ws = wb.create_sheet("KPI_Tracker")
    ws["A1"] = "Weekly KPI tracker: RAG vs target (green = on target, amber = within 25% of target, red = off target)"
    ws["A1"].font = Font(bold=True, size=13)
    ws["A3"], ws["A4"], ws["A5"], ws["A6"] = "Target defect rate", "Target mean cycle hrs", "Target recovery rate", "Target waste units / week"
    ws["B3"], ws["B4"], ws["B5"], ws["B6"] = m["target_defect_rate"], 12.0, 0.97, 5
    for c in ["B3", "B4", "B5", "B6"]:
        ws[c].fill = INPUT
    ws["B3"].number_format = "0.0%"
    ws["B5"].number_format = "0.0%"
    header(ws, 8, ["Week start", "Phase", "Defect rate", "Mean cycle hrs", "Recovery rate", "Waste units",
                   "Defect RAG", "Cycle RAG", "Recovery RAG", "Waste RAG"])
    k0 = 9
    for i, r in weekly.iterrows():
        x = k0 + i
        ws.cell(row=x, column=1, value=r.week_start.to_pydatetime()).number_format = "yyyy-mm-dd"
        ws.cell(row=x, column=2, value=f"=INDEX({wfr('B')},MATCH(A{x},{wfr('A')},0))")
        ws.cell(row=x, column=3, value=f"=INDEX({wfr('H')},MATCH(A{x},{wfr('A')},0))").number_format = "0.0%"
        ws.cell(row=x, column=4, value=f"=_xlfn.XLOOKUP(A{x},{wfr('A')},{wfr('I')})").number_format = "0.0"
        ws.cell(row=x, column=5, value=f"=INDEX({wfr('M')},MATCH(A{x},{wfr('A')},0))").number_format = "0.0%"
        ws.cell(row=x, column=6, value=f"=INDEX({wfr('N')},MATCH(A{x},{wfr('A')},0))")
        ws.cell(row=x, column=7, value=f'=IF(C{x}<=$B$3,"Green",IF(C{x}<=$B$3*1.25,"Amber","Red"))')
        ws.cell(row=x, column=8, value=f'=IF(D{x}<=$B$4,"Green",IF(D{x}<=$B$4*1.25,"Amber","Red"))')
        ws.cell(row=x, column=9, value=f'=IF(E{x}>=$B$5,"Green",IF(E{x}>=$B$5-0.01,"Amber","Red"))')
        ws.cell(row=x, column=10, value=f'=IF(F{x}<=$B$6,"Green",IF(F{x}<=$B$6*1.25,"Amber","Red"))')
    kl = k0 + len(weekly) - 1
    area = f"C{k0}:J{kl}"
    for word, fill in [("Green", GREEN), ("Amber", AMBER), ("Red", RED)]:
        ws.conditional_formatting.add(f"G{k0}:J{kl}", CellIsRule(operator="equal", formula=[f'"{word}"'], fill=fill))
    # metric cells pick up their RAG colour too
    for metric_col, rag_col in zip("CDEF", "GHIJ"):
        for word, fill in [("Green", GREEN), ("Amber", AMBER), ("Red", RED)]:
            ws.conditional_formatting.add(f"{metric_col}{k0}:{metric_col}{kl}",
                                          FormulaRule(formula=[f'${rag_col}{k0}="{word}"'], fill=fill))
    _ = area
    ws["L3"] = "Weeks Green on defect rate"
    ws["M3"] = f'=COUNTIF(G{k0}:G{kl},"Green")'
    ws["L4"] = "Weeks Red on defect rate"
    ws["M4"] = f'=COUNTIF(G{k0}:G{kl},"Red")'
    ws["L5"] = "Control-phase avg defect rate"
    ws["M5"] = f'=AVERAGEIFS(C{k0}:C{kl},B{k0}:B{kl},"Control")'
    ws["M5"].number_format = "0.0%"
    widths(ws, {"A": 26, "B": 10, "C": 11, "D": 13, "E": 12, "F": 11, "G": 11, "H": 11, "I": 12, "J": 11, "L": 28, "M": 10})
    ws.freeze_panes = f"A{k0}"
    kc = LineChart()
    kc.title = "Weekly defect rate vs target"
    kc.y_axis.number_format = "0%"
    kc.add_data(Reference(ws, min_col=3, min_row=8, max_row=kl), titles_from_data=True)
    kc.set_categories(Reference(ws, min_col=1, min_row=k0, max_row=kl))
    kc.height, kc.width = 8, 20
    ws.add_chart(kc, "L8")

    # ---------------------------------------------------------------- Scenario
    ws = wb.create_sheet("Scenario")
    ws["A1"] = "Scenario model: target defect rate -> annual recovery value impact"
    ws["A1"].font = Font(bold=True, size=13)
    rows = [
        ("Annual units processed", round(m["annual_units"]), "#,##0", "From v_units (12 months)"),
        ("Baseline defect rate", f'=SUMIFS({DEF},{PH},"Baseline")/COUNTIFS({PH},"Baseline")', "0.00%", "Audit_Data, phase = Baseline"),
        ("Target defect rate (INPUT)", m["target_defect_rate"], "0.00%", "Change this cell"),
        ("Avg leakage per defective unit ($)", f'=AVERAGEIFS({LEAK},{PH},"Baseline",{DEF},1)', '"$"#,##0.00', "Baseline audits, is_defect = 1"),
        ("Avg leakage per correct unit ($)", f'=AVERAGEIFS({LEAK},{PH},"Baseline",{DEF},0)', '"$"#,##0.00', "Baseline audits, is_defect = 0"),
        ("Incremental leakage per defect ($)", "=B6-B7", '"$"#,##0.00', "B6 - B7"),
        ("Defects avoided per year", "=MAX(0,(B4-B5))*B3", "#,##0", "(baseline - target) x units"),
        ("Annual recovery value protected ($)", "=B9*B8", '"$"#,##0', "defects avoided x leakage per defect"),
        ("Audit cost per unit audited ($) (INPUT)", 1.50, '"$"#,##0.00', "Assumption for QA labour"),
        ("Audit sample rate (INPUT)", 0.10, "0%", "Share of units audited"),
        ("Annual QA audit cost ($)", "=B3*B12*B11", '"$"#,##0', "units x rate x cost"),
        ("Net benefit after QA cost ($)", "=B10-B13", '"$"#,##0', "Recovery protected - QA cost"),
    ]
    header(ws, 2, ["Driver", "Value", "Source / note"])
    for i, (lab, val, fmt, note) in enumerate(rows, 3):
        ws.cell(row=i, column=1, value=lab)
        c = ws.cell(row=i, column=2, value=val)
        c.number_format = fmt
        ws.cell(row=i, column=3, value=note)
        if "INPUT" in lab:
            c.fill = INPUT
    for c in ["B10", "B14"]:
        ws[c].font = Font(bold=True)
    header(ws, 17, ["Target defect rate", "Defects avoided / yr", "Recovery $ protected / yr"])
    for i, t in enumerate([0.06, 0.05, 0.045, 0.04, 0.035, 0.03, 0.025, 0.02, 0.015, 0.01]):
        r = 18 + i
        ws.cell(row=r, column=1, value=t).number_format = "0.0%"
        ws.cell(row=r, column=2, value=f"=MAX(0,$B$4-A{r})*$B$3").number_format = "#,##0"
        ws.cell(row=r, column=3, value=f"=B{r}*$B$8").number_format = '"$"#,##0'
    widths(ws, {"A": 40, "B": 18, "C": 34})
    sc = BarChart()
    sc.title = "Annual recovery $ protected by target defect rate"
    sc.add_data(Reference(ws, min_col=3, min_row=17, max_row=27), titles_from_data=True)
    sc.set_categories(Reference(ws, min_col=1, min_row=18, max_row=27))
    sc.y_axis.number_format = '"$"#,##0'
    sc.height, sc.width = 8, 18
    ws.add_chart(sc, "E2")

    for sh in wb.worksheets:
        sh.sheet_view.showGridLines = sh.title in ("Audit_Data", "Weekly_Feed")
    wb.save(OUT)
    print(f"saved {OUT} ({OUT.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
